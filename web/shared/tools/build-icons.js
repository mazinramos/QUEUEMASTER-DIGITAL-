// Usage: npm i lucide-static  &&  node tools/build-icons.js <path-to-lucide-static/icons>
const fs = require('fs'), path = require('path');
const dir = process.argv[2] || path.join(process.cwd(), 'node_modules/lucide-static/icons');
const NAMES = ['ticket','users','user','clock','hourglass','check','circle-check','circle-x','x','phone','share-2','download',
  'printer','qr-code','refresh-cw','wifi-off','wifi','globe','log-out','log-in','bell','bell-ring','play','square-check',
  'skip-forward','undo-2','ban','arrow-right-left','search','scan-line','camera','lock','chevron-down','chevron-up',
  'chevron-right','chevron-left','loader','info','triangle-alert','copy','history','hash','stethoscope','megaphone','eye',
  'eye-off','key-round','message-square','map-pin','hospital','house','list','circle-alert','repeat','circle-play','bell-off','volume-2','volume-x','smartphone','keyboard','arrow-right','arrow-left','clock-3','circle-dot','list-ordered','plus','minus','settings','sliders-horizontal','trending-up','file-text','shield-check','shield-alert','flag','user-check','user-x','package-open','inbox','maximize','minimize'];
const out = {};
for (const n of NAMES) {
  const f = path.join(dir, n + '.svg');
  if (!fs.existsSync(f)) { console.error('missing icon', n); continue; }
  const svg = fs.readFileSync(f, 'utf8');
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s+/g, ' ').trim();
}
const src = `/* Generated by tools/build-icons.js from lucide-static (ISC licence, https://lucide.dev). Do not edit by hand. */
(function (root, factory) {
  var api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else { root.QM = root.QM || {}; root.QM.icons = api.icons; root.QM.icon = api.icon; }
})(typeof self !== 'undefined' ? self : this, function () {
  var icons = ${JSON.stringify(out, null, 1)};
  function icon(name, opts) {
    opts = opts || {};
    var inner = icons[name];
    if (inner == null) return '';
    var size = opts.size || 24;
    return '<svg class="qm-icon' + (opts.cls ? ' ' + opts.cls : '') + '" width="' + size + '" height="' + size +
      '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' + (opts.stroke || 1.75) +
      '" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + inner + '</svg>';
  }
  return { icons: icons, icon: icon };
});
`;
fs.writeFileSync(path.join(__dirname, '..', 'icons.js'), src);
console.log('icons:', Object.keys(out).length);
